import numpy as np

z = np.array([10, 20, 30, 40, 50])

print("Array:")
print(z)

print("\nGreater than 25:")
print(z > 25)

print("\nLess than 30:")
print(z < 30)

print("\nEqual to 30:")
print(z == 30)

print("\nNot equal to 30:")
print(z != 30)

print("\nGreater than or equal to 30:")
print(z >= 30)

print("\nLess than or equal to 30:")
print(z <= 30)